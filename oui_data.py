def normalize_oui_prefix(mac: str) -> str:
    """
    Extracts an OUI prefix in AA:BB:CC format from a MAC address.
    Accepts colon-separated, dash-separated, or plain hexadecimal MAC strings.
    """
    if not mac:
        return ""

    cleaned = re.sub(r"[^0-9A-Fa-f]", "", mac.strip())
    if len(cleaned) < 6 or not re.fullmatch(r"[0-9A-Fa-f]+", cleaned):
        return ""

    prefix = cleaned[:6].upper()
    return ":".join(prefix[index:index + 2] for index in range(0, 6, 2))


def lookup_vendor_by_mac(mac: str) -> str:
    """
    Returns a local best-effort vendor hint for a MAC address.
    Empty or invalid MAC values return an empty string; unknown valid OUIs return "Unknown".
    """
    prefix = normalize_oui_prefix(mac)
    if not prefix:
        return ""
    return OUI_VENDORS.get(prefix, "Unknown")
